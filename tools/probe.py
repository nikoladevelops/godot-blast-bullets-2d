#!/usr/bin/env python3
"""Run a GDScript snippet against the built plugin and print what it observed.

The one-command form of AGENTS.md §2.2 (probe before you claim): the snippet
runs as the body of a BlastTest test (so `factory`, `add()`, `idle()`,
`physics()`, `step_factory()`, `H` and `await` all work). Call
`probe(label, value)` to record a value; every line is written to disk at
once, so a snippet that hangs still shows how far it got. The errors and
warnings the snippet caused are printed too (nothing is claimed silently).
The probe files are always deleted afterwards.

    python3 tools/probe.py -c 'probe("size", AtlasTexture.new().get_size())'
    python3 tools/probe.py snippet.gd            # body from a file
    echo 'probe("x", 1 + 1)' | python3 tools/probe.py -
    python3 tools/probe.py --timeout 60 snippet.gd

Indent the snippet with tabs (4 leading spaces are converted to one tab).
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "test_project"
PROBE = PROJECT / "tests" / "spawner" / "test_zz_probe.gd"
OUTPUT = PROJECT / "test_results" / "probe_output.txt"

TEMPLATE = """extends BlastTest
## Generated by tools/probe.py: deleted after the run. Never commit.

var _probe_file: FileAccess


func probe(label, value = null) -> void:
	_probe_file.store_line(str(label) if value == null else "%s = %s" % [label, value])
	_probe_file.flush()


func test_probe() -> void:
	_probe_file = FileAccess.open("res://test_results/probe_output.txt", FileAccess.WRITE)
{body}
	for err in get_errors():
		if not err.handled:
			err.handled = true
			probe(("WARNING: " if err.is_push_warning() else "ERROR: ") + str(err.code))
	probe("PROBE DONE")
	_probe_file.close()
"""


def indent(body: str) -> str:
    lines = []
    for line in body.splitlines():
        m = re.match(r"^( {4})+", line)
        if m:
            line = "\t" * (len(m.group(0)) // 4) + line[len(m.group(0)):]
        lines.append("\t" + line if line.strip() else "")
    return "\n".join(lines) if lines else "\tpass"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("file", nargs="?", help="snippet file, or - for stdin")
    ap.add_argument("-c", dest="code", help="snippet text")
    ap.add_argument("--timeout", type=int, default=120, help="wall clock seconds (default 120)")
    args = ap.parse_args()
    if args.code is not None:
        body = args.code
    elif args.file == "-":
        body = sys.stdin.read()
    elif args.file:
        body = Path(args.file).read_text()
    else:
        ap.error("give a snippet file, - for stdin, or -c CODE")
    if PROBE.exists():
        print(f"{PROBE} already exists (another probe running?): not overwritten.", file=sys.stderr)
        return 2
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.unlink(missing_ok=True)
    PROBE.write_text(TEMPLATE.format(body=indent(body)))
    try:
        run = subprocess.run(
            [sys.executable, str(ROOT / "tools" / "run_tests.py"), "--suite", "test_zz_probe", "--full", "--no-lint", "--timeout", str(args.timeout)],
            cwd=ROOT, capture_output=True, text=True)
    finally:
        PROBE.unlink(missing_ok=True)
        Path(str(PROBE) + ".uid").unlink(missing_ok=True)
    out = OUTPUT.read_text() if OUTPUT.exists() else ""
    print(out, end="")
    if "PROBE DONE" not in out:
        # Crash, timeout, script error or a stale build: show the runner's verdict.
        print("--- the probe did not finish; runner output:")
        print("\n".join(l for l in run.stdout.splitlines() if l.strip())[-3000:])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
